const SVG = "http://www.w3.org/2000/svg";

/**
 * Icon `name` as an inline SVG element (built here: the window's policy allows no inline
 * markup from outside). With `title` it is labelled; without, hidden from screen readers.
 */
export function icon(name, className = "ic", title = "") {
  const svg = document.createElementNS(SVG, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("class", className);
  if (title) {
    const label = document.createElementNS(SVG, "title");
    label.textContent = title;
    svg.append(label);
  } else {
    svg.setAttribute("aria-hidden", "true");
  }
  const path = document.createElementNS(SVG, "path");
  path.setAttribute("d", ICONS[name] ?? "");
  svg.append(path);
  return svg;
}

/** Puts its icon at the front of every element marked `data-icon="name"`. */
export function drawIcons(root = document) {
  for (const element of root.querySelectorAll("[data-icon]")) {
    if (element.firstElementChild?.matches?.("svg.ic")) continue;
    element.prepend(icon(element.dataset.icon));
  }
}
